import { type PlanningInput, ProviderError } from "@testapp/core";
import {
  type DiscoverySummary,
  failPlanVersion,
  getLatestBrief,
  getPublicTarget,
  logEvent,
  savePlanContent,
  schema,
} from "@testapp/db";
import { and, desc, eq } from "drizzle-orm";
import type { WorkerContext } from "../context";

export async function latestDiscovery(
  ctx: WorkerContext,
  targetId: string,
): Promise<DiscoverySummary | null> {
  const [row] = await ctx.db
    .select({ discovery: schema.preflights.discovery })
    .from(schema.preflights)
    .where(and(eq(schema.preflights.targetId, targetId), eq(schema.preflights.status, "passed")))
    .orderBy(desc(schema.preflights.createdAt))
    .limit(1);
  return row?.discovery ?? null;
}

/** generate_plan job: build a sanitised planning input (no secrets) and persist the validated plan. */
export async function handleGeneratePlan(
  ctx: WorkerContext,
  payload: Record<string, string>,
): Promise<void> {
  const { targetId, planVersionId } = payload;
  if (!targetId || !planVersionId) throw new Error("generate_plan payload is missing ids");
  const target = await getPublicTarget(ctx.db, targetId);
  if (!target) throw new Error("target not found");
  const brief = await getLatestBrief(ctx.db, targetId);
  if (!brief) throw new Error("target has no brief");
  const env = ctx.env;
  const input: PlanningInput = {
    brief: brief.content,
    target: {
      name: target.name,
      baseUrl: target.baseUrl,
      startPath: target.startPath,
      authMode: target.authMode,
      allowDisposableWrites: target.allowDisposableWrites,
      prohibitedActionsSummary: target.prohibitedActionsSummary,
      roleNotes: target.roleNotes,
      buildLabel: target.buildLabel,
    },
    discovery: await latestDiscovery(ctx, targetId),
    limits: {
      maxPersonas: 5,
      maxScenarios: env.DEFAULT_MAX_SCENARIOS,
      maxActionsPerScenario: env.DEFAULT_MAX_ACTIONS_PER_SCENARIO,
    },
  };
  try {
    const result = await ctx.provider.generatePlan(input, {
      remainingInputTokens: env.DEFAULT_MAX_INPUT_TOKENS,
      remainingOutputTokens: env.DEFAULT_MAX_OUTPUT_TOKENS,
    });
    await savePlanContent(ctx.db, planVersionId, result.data, {
      tokenUsage: result.usage,
      model: result.model,
      notes: ctx.provider.isFake
        ? "Generated by the deterministic fake provider (no real LLM)."
        : "",
    });
    await logEvent(ctx.db, {
      targetId,
      type: "plan.generated",
      message: `plan generated by ${ctx.provider.name}: ${result.data.scenarios.length} scenarios`,
      data: { planVersionId, usage: result.usage, fake: ctx.provider.isFake },
    });
  } catch (err) {
    const message =
      err instanceof ProviderError
        ? `${err.kind}: ${err.message}`
        : err instanceof Error
          ? err.message
          : "plan generation failed";
    await failPlanVersion(ctx.db, planVersionId, message);
    await logEvent(ctx.db, {
      targetId,
      level: "error",
      type: "plan.failed",
      message,
      data: { planVersionId },
    });
    throw err;
  }
}
